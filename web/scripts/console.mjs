import { chromium } from 'playwright';
const [,, url] = process.argv;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=swiftshader','--enable-webgl','--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('console', m => { if (['error','warning'].includes(m.type())) console.log(m.type(), m.text().slice(0,200)); });
p.on('pageerror', e => console.log('pageerror', e.message.slice(0,300)));
p.on('requestfailed', r => console.log('reqfail', r.url().slice(0,100), r.failure()?.errorText));
await p.goto(url, { waitUntil: 'networkidle' }).catch(e=>console.log('goto',e.message));
await p.evaluate(() => window.scrollTo(0, 3000)); await p.waitForTimeout(4000);
console.log('webgl', await p.evaluate(() => !!document.createElement('canvas').getContext('webgl2')));
await b.close();
